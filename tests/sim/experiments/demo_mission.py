"""One-command demonstration: map the arena with SLAM, then run the whole rescue mission unattended, and write the results.

  ./run_demo.sh                              # the default scenario
  ./run_demo.sh --random 7                   # a NEW layout (fire, victims, obstacles) generated from seed 7, validated winnable
  ./run_demo.sh --scenario my.yaml           # any scenario YAML (same safe zone and robot start as the default)
  ./run_demo.sh --gui                        # watch it in Gazebo
  ./run_demo.sh --model nearest              # the nearest-first baseline instead of the risk-aware MVP
  ./run_demo.sh --map results/<run>/map/arena.yaml --scenario results/<run>/scenario.yaml   # skip mapping, reuse a saved map

Phase 1 (~3 min): arena + depth->/scan + scan-matching SLAM. The robot drives a lap and the map is saved. The lap is SCRIPTED
here from the scenario's geometry (the robot has no exploration behaviour for mapping); it is evaluation tooling, like the tests.
Phase 2 (~6-10 min): a fresh simulation, AMCL on the saved map, Nav2, perception, world model, cognition, magnet and the rescue
FSM, autostarted. Nobody touches anything: perception finds the victims, cognition picks the order, the FSM rescues them.

Results go to results/<scenario>_<time>/: report.md (start here), mission.png, map/, mission_state.json, decisions.jsonl,
world_state.json, trajectory.csv, summary.json, the scenario and world SDF, and the launch logs. Ground truth (Gazebo poses,
the scenario) is used ONLY to judge and plot; the mission has no access to it.
"""

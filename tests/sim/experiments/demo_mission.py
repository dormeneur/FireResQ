# ------------------------------------------------------------------------------------------------ scenarios
def random_scenario(seed, out_yaml):
    """A new layout from `seed`: the default arena, safe zone and robot start (the world model is configured with that safe
    zone), with a random fire, three victims (one close to the fire) and a partition plus two blocks. Retried until it passes the
    scenario validator, every victim is reachable, the mapping lap is drivable and risk-aware and nearest-first DISAGREE on the
    first rescue (so the demo shows cognition mattering)."""
    base = yaml.safe_load(resolve_scenario('default').read_text())
    rng = random.Random(seed)
    u = rng.uniform
    for _ in range(5000):
        fx, fy = u(-1.0, 1.5), u(-1.0, 1.5)          # away from the safe zone, and out of the corridor along the walls
        a = u(0, 2 * math.pi)
        r = u(0.5, 0.8)
        victims = [(fx + r * math.cos(a), fy + r * math.sin(a)), (u(-2.0, 2.0), u(-2.0, 2.0)), (u(-2.0, 2.0), u(-2.0, 2.0))]
        rng.shuffle(victims)
        length, vertical = u(1.0, 1.4), rng.random() < 0.5
        obstacles = [dict(name='obstacle_1', x=u(-1.3, 1.3), y=u(-1.3, 1.3), size_x=0.15 if vertical else length, size_y=length if vertical else 0.15)]
        for i in (2, 3):
            obstacles.append(dict(name=f'obstacle_{i}', x=u(-1.6, 1.6), y=u(-1.6, 1.6), size_x=u(0.3, 0.6), size_y=u(0.3, 0.6)))
        # keep a 0.5 m corridor along every wall, so the mapping lap can go round
        if any(abs(cx) > 2.0 or abs(cy) > 2.0 for o in obstacles for cx, cy in _corners(_obb(o['x'], o['y'], o['size_x'], o['size_y'], 0.0))):
            continue
        doc = dict(base, name=f'random_{seed}', description=f'Generated by demo_mission.py --random {seed}.',
                   fire={'model': 'fire', 'x': round(fx, 2), 'y': round(fy, 2)},
                   victims=[{'id': f'victim_{i + 1}', 'x': round(x, 2), 'y': round(y, 2)} for i, (x, y) in enumerate(victims)],
                   obstacles=[{k: round(v, 2) if isinstance(v, float) else v for k, v in o.items()} for o in obstacles])
        out_yaml.write_text(yaml.safe_dump(doc, sort_keys=False))
        try:
            sc = load_scenario(out_yaml)
        except ScenarioError:
            continue
        if not all(reachable(sc, v) for v in sc.victims) or mapping_route(sc) is None:
            continue
        orders = {m: offline_order(sc, m) for m in ('weighted_utility', 'nearest')}
        if len(orders['weighted_utility']) == 3 and orders['weighted_utility'][0] != orders['nearest'][0]:
            return sc
    raise SystemExit(f'no valid layout found for seed {seed}; try another seed')


def reachable(sc, v, standoff=0.4):
    oracle = ScenarioPathOracle(sc, clearance=0.22)
    s = (sc.robot_start.x, sc.robot_start.y)
    return any(oracle(s, (v.x + standoff * math.cos(a), v.y + standoff * math.sin(a))).ok for a in [k * math.pi / 6 for k in range(12)])


def check_compatible(sc):
    d = load_scenario(resolve_scenario('default'))
    if (sc.robot_start, sc.safe_zone, sc.arena) != (d.robot_start, d.safe_zone, d.arena):
        raise SystemExit('this demo keeps the default arena, safe zone and robot start (the world model is configured with that safe '
                         'zone: src/fire_resq_world_model/config/world_model.yaml); move the fire, victims and obstacles instead')


# ------------------------------------------------------------------------------------------------ the mapping lap
def mapping_route(sc):
    """WORLD waypoints for the SLAM lap: the proven lap on the default scenario; otherwise round the arena 0.5 m in from the walls
    (SE, NE, NW), through the middle and home, each leg A*-planned around the scenario's solids and pulled straight."""
    if sc.name == 'default':
        return list(LAP_WORLD)
    oracle = ScenarioPathOracle(sc, clearance=LAP_CLEARANCE_M)
    hx, hy = sc.arena.size_x / 2 - 0.5, sc.arena.size_y / 2 - 0.5
    start = (sc.robot_start.x, sc.robot_start.y)
    route, here = [], start
    for wp in [(hx, -hy), (hx, hy), (-hx, hy), (0.0, 0.0), start]:
        wp = snap_free(oracle, wp)
        p = oracle.path(here, wp) if wp else None
        if p is None:
            return None
        route += pull_straight(sc, p)[1:]
        here = route[-1] if route else here
    return route


def snap_free(oracle, p, max_r=0.6):
    i0, j0 = oracle._cell(p)
    for r in range(int(max_r / oracle.res) + 1):
        ring = [(i0 + di, j0 + dj) for di in range(-r, r + 1) for dj in range(-r, r + 1) if max(abs(di), abs(dj)) == r]
        free = [c for c in ring if oracle._inside(c) and not oracle.blocked[c[0]][c[1]]]
        if free:
            return oracle._centre(*min(free, key=lambda c: (c[0] - i0) ** 2 + (c[1] - j0) ** 2))
    return None


def pull_straight(sc, path):
    def clear(a, b):
        n = max(2, int(math.dist(a, b) / 0.03))
        return all(distance_to_surface(sc, a[0] + (b[0] - a[0]) * k / n, a[1] + (b[1] - a[1]) * k / n) >= LAP_CLEARANCE_M - 0.03
                   for k in range(n + 1))
    out, i = [path[0]], 0
    while i < len(path) - 1:
        j = next(j for j in range(len(path) - 1, i, -1) if j == i + 1 or clear(path[i], path[j]))
        out.append(path[j])
        i = j
    return [(round(x, 3), round(y, 3)) for x, y in out]


# ------------------------------------------------------------------------------------------------ offline reference
def offline_order(sc, model):
    """The rescue order `model` would choose with PERFECT knowledge (every victim known, true geometry, robot back at the start
    after each rescue). The live mission may differ: it discovers victims as it goes."""
    oracle, left, order = ScenarioPathOracle(sc), list(sc.victims), []
    s, f, z = sc.robot_start, sc.fire, sc.safe_zone
    while left:
        w = WorldView(0.0, tuple(VictimView(v.id, v.x, v.y, 1.0, DETECTED) for v in left), True, (f.x, f.y), (z.x, z.y), (s.x, s.y), s.yaw)
        d = make_prioritizer(model).select(w, PlanningContext(oracle))
        if d.selected is None:
            break
        order.append(d.selected.victim_id)
        left = [v for v in left if v.id != d.selected.victim_id]
    return order


# ------------------------------------------------------------------------------------------------ the mission
def run_mission(sc, scenario_yaml, map_yaml, model, gui, out):
    extra = [f'scenario:={scenario_yaml}', f'decision_model:={model}'] + (['gui:=true'] if gui else [])
    print('\n== Phase 2: the rescue mission (AMCL + Nav2 + perception + world model + cognition + magnet + rescue FSM) ==', flush=True)
    env = mission_bring_up(map_yaml, extra, victims=[v.id for v in sc.victims])
    res = dict(reports=[], final=None, world=None, truth={}, cmd=[], sim_s=0.0, wall_s=0.0, error=None)
    try:
        bot, tap = env.bot, env.tap
        bot.create_subscription(String, '/fire_resq/decision_report', lambda m: res['reports'].append(json.loads(m.data)), LATCHED)
        printed = [0]

        def show(snap):
            for h in snap['history'][printed[0]:]:
                print(f"  t={h[0]:7.1f}s  {h[1]:>22} -> {h[2]:<22} {h[4] or '':<4} {h[3]}", flush=True)
            printed[0] = len(snap['history'])
        tap.callbacks.append(show)
        t0, sim0 = time.time(), bot.simt
        tap.wait(lambda s: s['state'] != 'INIT', 300, 'the mission to start')
        while time.time() - t0 < MISSION_WALL_BUDGET_S and tap.state not in TERMINAL_STATES:
            bot.spin_wall(0.5)
        if tap.state not in TERMINAL_STATES:
            res['error'] = f'the mission did not finish within {MISSION_WALL_BUDGET_S:.0f} s wall time'
        res.update(sim_s=bot.simt - sim0, wall_s=time.time() - t0)
        bot.spin_wall(3.0)                                   # let the last physics settle before the truth snapshot
    except Exception as e:                                   # keep whatever was recorded: a failed run is still evidence
        res['error'] = f'{type(e).__name__}: {e}'
    finally:
        res.update(final=env.tap.last, world=env.bot.world, cmd=list(env.tap.cmd),
                   truth={n: env.truth.track(n) for n in ['fire_resq', *[v.id for v in sc.victims]]})
        shutil.copy(env.sim.log_path, out / 'logs' / 'mission_launch.log')
        mission_teardown(env)
    return res


# ------------------------------------------------------------------------------------------------ outputs
def load_map(map_yaml):
    from PIL import Image
    meta = yaml.safe_load(Path(map_yaml).read_text())
    img = Image.open(Path(map_yaml).parent / meta['image'])
    w, h = img.size
    px = list(img.getdata())
    res, (ox, oy, _) = meta['resolution'], meta['origin']
    occ, free = [], []
    for k, p in enumerate(px):
        r, c = divmod(k, w)
        x, y = ox + (c + 0.5) * res, oy + (h - r - 0.5) * res
        v = (255 - p) / 255.0
        if v > meta['occupied_thresh']:
            occ.append((x, y))
        elif v < meta['free_thresh']:
            free.append((x, y))
    return occ, free, res


def inside_zone(sc, x, y, margin=0.03):
    z = sc.safe_zone
    return abs(x - z.x) <= z.size_x / 2 - margin and abs(y - z.y) <= z.size_y / 2 - margin


def plot(sc, occ_w, route, res, ids, order, path_png):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.patches import Circle, Polygon, Rectangle
    fig, ax = plt.subplots(figsize=(9, 9))
    hx, hy = sc.arena.size_x / 2, sc.arena.size_y / 2
    ax.add_patch(Rectangle((-hx, -hy), 2 * hx, 2 * hy, fill=False, lw=3, color='0.4'))
    z = sc.safe_zone
    ax.add_patch(Rectangle((z.x - z.size_x / 2, z.y - z.size_y / 2), z.size_x, z.size_y, color='#3cb44b', alpha=0.3, label='safe zone'))
    for o in sc.obstacles:
        ax.add_patch(Polygon(_corners(_obb(o.x, o.y, o.size_x, o.size_y, o.yaw)), color='0.55', alpha=0.6))
    if occ_w:
        ax.scatter(*zip(*occ_w), s=2, c='k', marker='s', label='SLAM map: occupied cells')
    ax.add_patch(Circle((sc.fire.x, sc.fire.y), 0.15, color='#ff7f0e', label='fire'))
    if route:
        xs, ys = zip(*([(sc.robot_start.x, sc.robot_start.y)] + route))
        ax.plot(xs, ys, '--', c='#911eb4', lw=1, label='mapping lap (phase 1)')
    rob = res['truth'].get('fire_resq') or []
    if rob:
        ax.plot([p[1] for p in rob], [p[2] for p in rob], c='#4363d8', lw=1.2, alpha=0.8, label='robot during the mission (truth)')
    for v in sc.victims:
        ax.add_patch(Circle((v.x, v.y), 0.07, color='#000075'))
        rank = f'#{order.index(v.id) + 1} ' if v.id in order else ''
        ax.annotate(f'{rank}{v.id} ({ids.get(v.id) or "?"})', (v.x, v.y), xytext=(6, 8), textcoords='offset points', fontsize=10, weight='bold')
        tr = res['truth'].get(v.id) or []
        if tr and math.dist((tr[-1][1], tr[-1][2]), (v.x, v.y)) > 0.1:
            ax.annotate('', (tr[-1][1], tr[-1][2]), (v.x, v.y), arrowprops=dict(arrowstyle='->', color='#e6194b', lw=1.2))
            ax.plot(tr[-1][1], tr[-1][2], 'x', c='#e6194b', ms=8)
    ax.plot(sc.robot_start.x, sc.robot_start.y, '^', c='#4363d8', ms=10, label='robot start')
    ax.set_xlim(-hx - 0.2, hx + 0.2)
    ax.set_ylim(-hy - 0.2, hy + 0.2)
    ax.set_aspect('equal')
    ax.grid(alpha=0.3)
    ax.set_title(f'FireResQ: {sc.name} - rescue order #1..#{len(order)} (red arrows: where each victim was carried)')
    ax.legend(loc='upper left', fontsize=8, framealpha=0.9)
    fig.tight_layout()
    fig.savefig(path_png, dpi=110)
    plt.close(fig)


def write_results(sc, model, out, map_yaml, route, res, mapping_s):
    final = res['final'] or {}
    hist = final.get('history', [])
    world = res['world']
    # scenario victim -> world model id, matched by POSITION (the world model numbers victims in the order it found them)
    ids = {v.id: (victim_id_by_position(world, sc.world_to_odom(v.x, v.y)) if world else None) for v in sc.victims}
    by_wm = {wm: sid for sid, wm in ids.items() if wm}
    rescued_order = [by_wm.get(h[4], h[4]) for h in hist if h[1] == 'VERIFY_RELEASE' and h[2] == 'REASSESS']
    selections = [h for h in hist if h[1] == 'SELECT_TARGET' and h[2] == 'NAVIGATE_TO_APPROACH']
    expected = {m: offline_order(sc, m) for m in ('weighted_utility', 'nearest')}

    # the decision behind each selection: the last report, before it, that chose that victim
    def report_for(h):
        cands = [r for r in res['reports'] if r.get('selected') == h[4]]
        before = [r for r in cands if r.get('world', {}).get('stamp', 0) <= h[0] + 0.5]
        return (before or cands or [None])[-1]

    truth_end = {v.id: (res['truth'][v.id][-1] if res['truth'].get(v.id) else None) for v in sc.victims}
    in_zone = {k: (t is not None and inside_zone(sc, t[1], t[2])) for k, t in truth_end.items()}
    occ, free, cell = load_map(map_yaml)
    occ_w = [sc.odom_to_world(x, y) for x, y in occ]
    on_surface = sum(distance_to_surface(sc, x, y) <= 0.10 for x, y in occ_w) / max(len(occ_w), 1)
    min_vx = min((c[1] for c in res['cmd']), default=0.0)
    success = final.get('state') == 'MISSION_COMPLETE' and all(in_zone.values())

    summary = dict(scenario=sc.name, decision_model=model, success=success, state=final.get('state'), reason=final.get('reason'),
                   error=res['error'], sim_seconds=round(res['sim_s'], 1), wall_seconds=round(res['wall_s'], 1),
                   mapping_wall_seconds=round(mapping_s, 1), rescued_order=rescued_order, given_up=final.get('given_up'),
                   expected_order_with_perfect_knowledge=expected, world_model_ids=ids,
                   victims_inside_safe_zone_by_ground_truth=in_zone, metrics=final.get('metrics'), search_coverage=final.get('coverage'),
                   map=dict(cells_occupied=len(occ), free_area_m2=round(len(free) * cell * cell, 2),
                            occupied_cells_within_10cm_of_a_true_surface=round(on_surface, 3)),
                   never_reversed=min_vx >= -1e-6, decisions_published=len(res['reports']))
    (out / 'summary.json').write_text(json.dumps(summary, indent=2))
    (out / 'mission_state.json').write_text(json.dumps(final, indent=2))
    with open(out / 'decisions.jsonl', 'w') as f:
        for r in res['reports']:
            f.write(json.dumps(r) + '\n')
    if world:
        (out / 'world_state.json').write_text(json.dumps(dict(
            fire_known=world.fire_known, fire=[world.fire_position.x, world.fire_position.y] if world.fire_known else None,
            victims=[dict(id=v.id, scenario_id=by_wm.get(v.id), status=STATUS.get(v.status, v.status), x=round(v.position.x, 3),
                          y=round(v.position.y, 3), confidence=round(v.confidence, 3)) for v in world.victims]), indent=2))
    with open(out / 'trajectory.csv', 'w', newline='') as f:
        wr = csv.writer(f)
        wr.writerow(['entity', 't_wall_s', 'x_world', 'y_world', 'z', 'yaw'])
        t0 = min((tr[0][0] for tr in res['truth'].values() if tr), default=0.0)
        for name, tr in res['truth'].items():
            last = -1.0
            for t, x, y, z, yaw in tr:
                if t - last >= 0.2:                          # 5 Hz is plenty
                    wr.writerow([name, round(t - t0, 2), round(x, 3), round(y, 3), round(z, 3), round(yaw, 3)])
                    last = t
    plot(sc, occ_w, route, res, ids, rescued_order, out / 'mission.png')

    # ---- report.md
    L = [f'# FireResQ demo: scenario `{sc.name}`, decision model `{model}`', '',
         f"**Result: {'SUCCESS' if success else 'NOT A FULL SUCCESS'}** - final state `{final.get('state')}` ({final.get('reason')})"
         + (f"; error: {res['error']}" if res['error'] else ''), '',
         f"Mission: {res['sim_s']:.0f} s simulated, {res['wall_s']:.0f} s wall. Mapping lap: {mapping_s:.0f} s wall.", '',
         '![mission](mission.png)', '', '## Layout (ground truth, for evaluation only; the robot never reads it)', '', '```',
         ascii_map(sc), '```', 'R robot start, `.` safe zone, X obstacle, F fire, digits = victims.', '',
         '| entity | x | y | distance to fire |', '|---|---|---|---|']
    for v in sc.victims:
        L.append(f'| {v.id} | {v.x:.2f} | {v.y:.2f} | {math.dist((v.x, v.y), (sc.fire.x, sc.fire.y)):.2f} m |')
    L += [f'| fire | {sc.fire.x:.2f} | {sc.fire.y:.2f} | |', '', '## Rescue order', '',
          f'- **Live mission ({model})**: ' + (' -> '.join(f'{v} ({ids.get(v)})' for v in rescued_order) or 'none'),
          f"- Reference, risk-aware MVP with perfect knowledge: {' -> '.join(expected['weighted_utility'])}",
          f"- Reference, nearest-first with perfect knowledge: {' -> '.join(expected['nearest'])}", '',
          'The live mission only knows what its camera has seen, so a victim hidden behind an obstacle is found later by the '
          'search and can be rescued later than the perfect-knowledge reference.', '',
          '## Ground-truth check (Gazebo poses after the mission)', '', '| victim | world model id | final position | inside safe zone |', '|---|---|---|---|']
    for v in sc.victims:
        t = truth_end[v.id]
        L.append(f"| {v.id} | {ids.get(v.id)} | {f'({t[1]:.2f}, {t[2]:.2f})' if t else '?'} | {'yes' if in_zone[v.id] else 'NO'} |")
    L += ['', f"Never reversed: {'yes' if summary['never_reversed'] else 'NO'}. Given up: {final.get('given_up')}.", '',
          '## Every rescue decision (cognition, live)', '',
          'Utility = sum of weighted factor contributions; the highest eligible utility is chosen. Positions are in the `map` frame.', '']
    for n, h in enumerate(selections, 1):
        r = report_for(h)
        L.append(f'### Selection {n} at t={h[0]:.1f} s: {h[4]} ({by_wm.get(h[4], "?")})')
        if not r:
            L += ['(no decision report captured)', '']
            continue
        L += ['', '| candidate | utility | contributions | note |', '|---|---|---|---|']
        for c in r['candidates']:
            contrib = ', '.join(f'{k} {v:+.2f}' for k, v in c['contributions'].items())
            note = c['exclusion'] or c['rationale']
            u = f"{c['utility']:+.3f}" if c['utility'] is not None else '-'
            L.append(f"| {c['victim_id']} ({by_wm.get(c['victim_id'], '?')}) | {u} | {contrib} | {note} |")
        L.append('')
    sc_dec, _, _ = evaluate(sc)
    L += ['## Offline reference: the first decision with perfect knowledge', '', '```', table(sc_dec['weighted_utility']), '',
          table(sc_dec['nearest']), '```', '', '## SLAM map', '',
          f'`map/arena.pgm` + `map/arena.yaml`: {len(occ)} occupied cells, {summary["map"]["free_area_m2"]} m2 mapped free. '
          f'{on_surface:.0%} of occupied cells lie within 10 cm of a real surface (raw, no alignment).', '',
          '## Mission metrics', '', '```', json.dumps(final.get('metrics'), indent=2), f"search coverage: {final.get('coverage')}", '```', '',
          '## State timeline', '', '| t (s) | from | to | target | reason |', '|---|---|---|---|---|']
    L += [f'| {h[0]:.1f} | {h[1]} | {h[2]} | {h[4] or ""} | {h[3]} |' for h in hist]
    L += ['', '## Files', '',
          '- `summary.json` machine-readable outcome', '- `mission_state.json` the FSM\'s final snapshot with the full transition history',
          '- `decisions.jsonl` every decision cognition published (candidates, factors, contributions, the exact world it saw)',
          '- `world_state.json` the world model\'s final belief', '- `trajectory.csv` true robot and victim poses, 5 Hz',
          '- `map/` the saved SLAM map', '- `scenario.yaml`, `world.sdf` the layout (rerun with `--scenario`)', '- `logs/` launch logs']
    (out / 'report.md').write_text('\n'.join(L) + '\n')
    return summary



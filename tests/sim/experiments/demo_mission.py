def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--scenario', default='default', help='scenario name or YAML path')
    ap.add_argument('--random', type=int, metavar='SEED', help='generate a new layout from this seed (overrides --scenario)')
    ap.add_argument('--model', default='weighted_utility', choices=('weighted_utility', 'nearest'))
    ap.add_argument('--map', help='reuse a saved map (.yaml) of THIS scenario and skip mapping')
    ap.add_argument('--gui', action='store_true', help='show Gazebo')
    ap.add_argument('--out', default=str(REPO / 'results'))
    a = ap.parse_args()

    tag = f'random_{a.random}' if a.random is not None else Path(a.scenario).stem
    out = Path(a.out) / f"{tag}_{a.model}_{time.strftime('%Y%m%d-%H%M%S')}"
    (out / 'logs').mkdir(parents=True)
    (out / 'map').mkdir()
    scenario_yaml = out / 'scenario.yaml'
    if a.random is not None:
        print(f'Generating a random layout from seed {a.random} ...', flush=True)
        sc = random_scenario(a.random, scenario_yaml)
    else:
        shutil.copy(resolve_scenario(a.scenario), scenario_yaml)
        sc = load_scenario(scenario_yaml)
    check_compatible(sc)
    write_world(sc, out / 'world.sdf')
    print(ascii_map(sc))
    print(f'Results will be written to {out}', flush=True)

    rclpy.init()
    try:
        route, t0 = mapping_route(sc), time.time()
        if a.map:
            for f in Path(a.map).parent.glob(Path(a.map).stem + '.*'):
                shutil.copy(f, out / 'map' / f.name)
            map_yaml = out / 'map' / Path(a.map).name
        else:
            if route is None:
                raise SystemExit('could not plan a mapping lap round this layout')
            print(f'\n== Phase 1: SLAM mapping lap ({len(route)} legs) ==', flush=True)
            extra = [f'scenario:={scenario_yaml}'] + (['gui:=true'] if a.gui else [])
            map_yaml = map_arena(sc, route, out / 'map' / 'arena', extra,
                                 on_waypoint=lambda i, env: print(f'  leg {i + 1}/{len(route)} done', flush=True))
            print(f'  map saved: {map_yaml}', flush=True)
        mapping_s = time.time() - t0
        res = run_mission(sc, scenario_yaml, map_yaml, a.model, a.gui, out)
    finally:
        rclpy.shutdown()
    s = write_results(sc, a.model, out, map_yaml, route, res, mapping_s)
    print(f"\n{'SUCCESS' if s['success'] else 'NOT A FULL SUCCESS'}: {s['state']}; rescued in order {s['rescued_order']} "
          f"(perfect-knowledge reference {s['expected_order_with_perfect_knowledge'][a.model]}); "
          f"inside the safe zone: {s['victims_inside_safe_zone_by_ground_truth']}")
    print(f'Report: {out / "report.md"}\nPlot:   {out / "mission.png"}')
    return 0 if s['success'] else 1


if __name__ == '__main__':
    sys.exit(main())
